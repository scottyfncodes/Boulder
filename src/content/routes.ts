export const ROUTES_BY_ID: Map<string, Route> = new Map(ROUTES.map((r) => [r.id, r]));

export function routeById(id: string): Route | undefined {
  return ROUTES_BY_ID.get(id) ?? LAB_ROUTES.find((r) => r.id === id) ?? generatedRouteById(id);
}
